// Rebuilds the data the design bible draws from: every shared/*.json the game reads, the
// implementation tracker (design/status.json), and a map of the island rendered by the real
// terrain generator. Run `npm run design` after changing any of them.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));

// The map: bundle design/map.ts (it imports the TypeScript terrain generator) and run it.
const tmp = mkdtempSync(join(tmpdir(), 'ruina-design-'));
const bundle = join(tmp, 'map.mjs');
execFileSync(join(root, 'node_modules/.bin/rolldown'), [join(root, 'design/map.ts'), '--file', bundle, '--format', 'esm', '--platform', 'node'], {
  cwd: root,
  stdio: ['ignore', 'ignore', 'inherit'],
});
const { renderMap } = await import(pathToFileURL(bundle).href);
const map = renderMap(640);
rmSync(tmp, { recursive: true, force: true });

const zone = read('shared/zones/emberholm.json');
const tuning = read('shared/tuning.json');
const data = {
  built: new Date().toLocaleDateString('en-CA'), // local YYYY-MM-DD
  vehicles: read('shared/vehicles.json'),
  farming: read('shared/farming.json'),
  trade: read('shared/trade.json'),
  items: read('shared/items.json'),
  housing: read('shared/housing.json'),
  shipyard: read('shared/shipyard.json'),
  quests: read('shared/quests.json'),
  traversal: read('shared/traversal.json'),
  structures: read('shared/structures.json').structures.map((s) => ({ id: s.id, name: s.name, w: s.w, d: s.d, h: s.h })),
  tuning: {
    move: tuning.move,
    jump: tuning.jump,
    weapons: tuning.weapons.map((w) => ({ name: w.name, hits: w.combo.length, damage: w.combo.map((c) => c.damage) })),
    abilities: tuning.abilities.map((a) => ({ name: a.name, icon: a.icon, desc: a.desc, cast: a.castFrames, cooldown: a.cooldownFrames })),
    movementSkills: tuning.movementSkills.map((m) => ({ name: m.name, icon: m.icon, desc: m.desc })),
    trees: tuning.skills.trees.map((t) => t.name),
    nodes: tuning.skills.nodes.length,
    points: tuning.skills.points,
  },
  zone: {
    name: zone.name,
    subtitle: zone.subtitle,
    climate: zone.climate,
    places: zone.places,
    npcs: zone.npcs,
    outposts: zone.outposts,
    workbenches: zone.workbenches,
    housePlots: zone.housePlots,
    updrafts: zone.updrafts,
    nodes: zone.nodes,
    farmland: zone.farmland,
    spawn: zone.spawn,
    map: { size: map.size, half: map.half, roads: map.roads, ramps: map.ramps, stats: map.stats },
  },
  status: read('design/status.json'),
};

const page = join(root, 'design/index.html');
const html = readFileSync(page, 'utf8');
const block =
  '<!-- BEGIN:DATA (generated by design/build.mjs - edit the sources, not this) -->\n' +
  `<script type="application/json" id="bible-data">${JSON.stringify(data).replace(/</g, '\\u003c')}</script>\n` +
  `<img hidden id="bible-map" alt="" src="data:image/png;base64,${map.png}">\n` +
  '<!-- END:DATA -->';
const next = html.replace(/<!-- BEGIN:DATA[\s\S]*?<!-- END:DATA -->/, block);
if (next === html && !html.includes('BEGIN:DATA')) throw new Error('design/index.html has no BEGIN:DATA / END:DATA markers');
writeFileSync(page, next);
console.log(`design/index.html rebuilt (${(next.length / 1024).toFixed(0)} KB, map ${map.size}px, ${data.status.features.length} tracked features)`);
